import { useEffect, useRef } from "react";
import { Markdown } from "../lib/markdown";
import type { ChatMetadata, ThreadItem } from "../lib/types";
import { IconClock, IconCpu, IconInfo, IconKey, IconLayers, IconRetry } from "./Icons";

export function MetaStrip({ meta }: { meta: Partial<ChatMetadata> }) {
  const source = meta.resolution_source ?? "LIVE_INFERENCE";
  const isCache = source === "LLM_CACHE";
  const attempts = meta.fallback_attempts ?? 0;
  return (
    <div className="meta" aria-label="Response metadata">
      <span className={`meta-chip meta-source ${isCache ? "is-cache" : "is-live"}`} title={isCache ? "Served from LiteLLM's cache" : "Generated by a live model call"}>
        <span className="meta-dot" aria-hidden="true" />
        <span data-testid="meta-source">{source}</span>
      </span>
      <span className="meta-chip" title="Model that produced the reply">
        <IconCpu />
        <span data-testid="meta-model">{meta.model ?? "unknown"}</span>
      </span>
      <span className="meta-chip" title="Server-measured latency for this request">
        <IconClock />
        <span data-testid="meta-latency">{`${meta.latency_ms ?? 0} ms`}</span>
      </span>
      <span className="meta-chip" title="Tokens for this request only">
        <IconLayers />
        <span className="meta-lbl">IN</span>
        <span data-testid="meta-input-tokens">{meta.input_tokens ?? 0}</span>
        <span className="meta-lbl">OUT</span>
        <span data-testid="meta-output-tokens">{meta.output_tokens ?? 0}</span>
      </span>
      <span className="meta-chip" title={meta.key_id ? "API key that answered" : "No key used: answered from cache"}>
        <IconKey />
        <span data-testid="meta-key-id">{meta.key_id ?? "no key"}</span>
      </span>
      {attempts > 0 && (
        <span className="meta-chip is-failover" data-testid="meta-fallback" title="Keys that failed before this one answered">
          <IconRetry />
          {attempts} failover{attempts > 1 ? "s" : ""}
        </span>
      )}
    </div>
  );
}

interface ThreadProps {
  items: ThreadItem[];
  pending: boolean;
  pendingLabel: string;
  onRetry: (item: Extract<ThreadItem, { kind: "error" }>) => void;
}

export function Thread({ items, pending, pendingLabel, onRetry }: ThreadProps) {
  const listRef = useRef<HTMLDivElement>(null);

  // Scroll only the thread itself (scrollIntoView could also nudge the page sideways).
  useEffect(() => {
    const el = listRef.current;
    if (el) el.scrollTo({ top: el.scrollHeight, behavior: "smooth" });
  }, [items.length, pending]);

  return (
    <div className="thread" ref={listRef} role="log" aria-live="polite" aria-label="Conversation">
      {items.map((item) => {
        if (item.kind === "user") {
          return (
            <div key={item.id} className="msg msg-user">
              <div className="bubble">{item.text}</div>
            </div>
          );
        }
        if (item.kind === "assistant") {
          return (
            <div key={item.id} className="msg msg-assistant" data-testid="assistant-message">
              <span className="avatar-orb" aria-hidden="true" />
              <div className="msg-body">
                <Markdown text={item.text} />
                <MetaStrip meta={item.meta} />
              </div>
            </div>
          );
        }
        return (
          <div key={item.id} className="msg msg-error" data-testid="error-message" role="alert">
            <span className="error-icon" aria-hidden="true"><IconInfo /></span>
            <div className="msg-body">
              <p>{item.text}</p>
              {item.retry && (
                <button className="retry" onClick={() => onRetry(item)}>
                  <IconRetry /> Retry
                </button>
              )}
            </div>
          </div>
        );
      })}
      {pending && (
        <div className="msg msg-assistant is-typing" aria-label={pendingLabel}>
          <span className="avatar-orb is-pulsing" aria-hidden="true" />
          <div className="typing">
            <span className="typing-dots" aria-hidden="true"><i /><i /><i /></span>
            <span className="typing-label">{pendingLabel}</span>
          </div>
        </div>
      )}
    </div>
  );
}
